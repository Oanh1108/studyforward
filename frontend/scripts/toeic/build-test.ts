/**
 * Builds the dictation data for one TOEIC test from its transcript and the speech-recognition output of its recordings.
 *
 *   node scripts/toeic/build-test.ts --year 2026 --test 7 \
 *        --script data/toeic/2026/test-07.script.txt --asr <dir with asr-part1.json ... asr-part4.json>
 *
 * Writes lib/dictation/toeic/<year>-test-<nn>.ts and prints a report of sentences that could not be located
 * confidently in the audio, so they can be checked by ear.
 */
import fs from 'node:fs';
import path from 'node:path';
import { alignScript, clipsFromAlignment, type TimedWord } from '../../lib/dictation/align.ts';
import { buildItems, parseScript } from '../../lib/dictation/toeic/script.ts';
import type { ToeicPart, ToeicTest } from '../../lib/dictation/toeic/types.ts';

const arg = (name: string) => {
  const i = process.argv.indexOf(`--${name}`);
  if (i === -1 || !process.argv[i + 1]) throw new Error(`missing --${name}`);
  return process.argv[i + 1];
};

const year = Number(arg('year'));
const testNo = Number(arg('test'));
const scriptPath = arg('script');
const asrDir = arg('asr');
const nn = String(testNo).padStart(2, '0');
// Some tests (2023) only have Parts 1 and 2: pass --parts 1,2
const PARTS = (process.argv.includes('--parts') ? arg('parts').split(',').map(Number) : [1, 2, 3, 4]) as ToeicPart[];
const audioBase = `/audio/toeic/${year}/test-${nn}`;

const items = buildItems(parseScript(fs.readFileSync(scriptPath, 'utf8'))).filter((i) => PARTS.includes(i.part));
const MIN_CONFIDENCE = 0.7;
let located = 0;
let total = 0;
const doubtful: string[] = [];

for (const part of PARTS) {
  const partItems = items.filter((i) => i.part === part);
  const asrFile = path.join(asrDir, `asr-part${part}.json`);
  if (!fs.existsSync(asrFile)) throw new Error(`missing ${asrFile}`);
  const asr = JSON.parse(fs.readFileSync(asrFile, 'utf8')) as { duration: number; chunks: { text: string; timestamp: [number, number] }[] };
  const words: TimedWord[] = asr.chunks.map((c) => ({ text: c.text, start: c.timestamp[0], end: c.timestamp[1] ?? c.timestamp[0] }));

  const segments = partItems.flatMap((item) => item.segments);
  const aligned = alignScript(segments.map((s) => ({ id: s.id, text: s.text })), words);
  const clips = clipsFromAlignment(aligned, asr.duration);

  segments.forEach((segment, i) => {
    total++;
    const clip = clips[i];
    const a = aligned[i];
    if (clip) {
      segment.clip = clip;
      located++;
    }
    if (!clip || a.matched / a.total < MIN_CONFIDENCE) {
      doubtful.push(`${segment.id} ${clip ? `[${clip.start}-${clip.end}] ${a.matched}/${a.total}` : 'NOT FOUND'} "${segment.text}"`);
    }
  });
}

const test: ToeicTest = {
  id: `toeic-${year}-test-${nn}`,
  year,
  test: testNo,
  title: `ETS ${year} · Test ${testNo}`,
  audio: Object.fromEntries(PARTS.map((p) => [p, `${audioBase}/part-${p}.mp3`])),
  items,
};

const exportName = `toeic${year}Test${nn}`;
const out = path.join('lib', 'dictation', 'toeic', `${year}-test-${nn}.ts`);
fs.writeFileSync(
  out,
  `// Generated by scripts/toeic/build-test.ts from ${scriptPath}. Re-run the script instead of editing by hand.\n` +
    `import type { ToeicTest } from './types.ts';\n\n` +
    `export const ${exportName}: ToeicTest = ${JSON.stringify(test, null, 2)};\n`,
);

console.log(`${out}: ${items.length} items, ${located}/${total} sentences located in the audio`);
if (doubtful.length) {
  console.log(`\n${doubtful.length} sentence(s) to check by ear (not found, or under ${MIN_CONFIDENCE * 100}% of words recognised):`);
  doubtful.forEach((d) => console.log('  ' + d));
}
